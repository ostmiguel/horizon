-- ── Убрать легаси счета-строки «Доход»/«Расход» ──────────────────────────────
-- Доход/Расход — магические строки (хардкод в формах, метрики трактуют как поток),
-- счетами быть не должны. У одного старого пользователя они остались строками
-- accounts типа «Поток» от древнего сида — разнобой скелета. Сносим: операции
-- ссылаются на «Доход»/«Расход» по ИМЕНИ-строке (в transactions нет account_id на
-- них), поэтому удаление строки безопасно и ничего не осиротит. Пользователи не
-- могут создавать потоковые счета, а имена системные — легитимных совпадений нет.
-- Идемпотентно. Делает скелет однородным (маг-строки без счетов у всех).

DELETE FROM accounts
WHERE name IN ('Доход', 'Расход') AND account_type = 'Поток';
