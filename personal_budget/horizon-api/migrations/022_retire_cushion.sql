-- Migration 022 — упраздняем понятие «подушка» (is_cushion)
-- Код больше не использует is_cushion. Любой существующий cushion-счёт делаем
-- обычным резервом, чтобы его баланс остался «отложенным» (в резерве), а не
-- превратился в операционный/капитальный. Столбец is_cushion НЕ удаляем: на него
-- ссылаются старые миграции 001/013/018, которые прогоняются на каждом деплое.
--
-- Идемпотентно (после первого прогона строк под условие нет) и ограничено
-- (WHERE is_cushion) — безопасно при повторных запусках каждый деплой.
UPDATE accounts
   SET is_reserve = true
 WHERE is_cushion = true
   AND is_reserve = false;
