-- ── Пожизненный доступ всем ТЕКУЩИМ пользователям (до запуска оплаты) ─────────
-- Оплата (ЮKassa) ещё не подключена: после 35-дневного триала пользователь
-- упирается в блок без возможности заплатить. Чтобы никого не заблокировать,
-- выдаём is_free_forever всем, кто уже зарегистрирован на момент применения.
--
-- Грант делаем НАПРЯМУЮ (как для владельца в 012), а не погашением промокода
-- LIKEABOSS: тот лимитирован 25 слотами и сгорел бы при большем числе людей.
-- Промо-слоты (SUMMER50 / LIKEABOSS) остаются нетронутыми.
--
-- ВНИМАНИЕ: деплой прогоняет ВСЕ migrations/*.sql на КАЖДОМ пуше (таблицы учёта
-- применённых миграций нет). Поэтому одного «WHERE is_free_forever = false» мало:
-- без временной границы миграция заново штамповала бы free_forever всем новым
-- триальным пользователям при каждом деплое. Жёстко ограничиваем когортой,
-- существовавшей на момент авторства миграции (2026-07-06 15:00 MSK). Все, кто
-- зарегистрировался ПОСЛЕ, проходят обычный триал 35 дней (и промо при желании).
-- created_at — TIMESTAMPTZ, литерал с явной зоной → сравнение однозначно.

UPDATE users
SET is_free_forever = true
WHERE is_free_forever = false
  AND created_at < TIMESTAMPTZ '2026-07-06 15:00:00+03';
