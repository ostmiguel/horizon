-- ── Пожизненный доступ всем ТЕКУЩИМ пользователям (до запуска оплаты) ─────────
-- Оплата (ЮKassa) ещё не подключена: после 35-дневного триала пользователь
-- упирается в блок без возможности заплатить. Чтобы никого не заблокировать,
-- выдаём is_free_forever всем, кто уже зарегистрирован на момент применения.
--
-- Грант делаем НАПРЯМУЮ (как для владельца в 012), а не погашением промокода
-- LIKEABOSS: тот лимитирован 25 слотами и сгорел бы при большем числе людей.
-- Промо-слоты (SUMMER50 / LIKEABOSS) остаются нетронутыми.
--
-- Миграция разовая: затрагивает только существующие строки. Пользователи,
-- зарегистрированные ПОСЛЕ применения, проходят обычный триал 35 дней.
-- Идемпотентно (WHERE is_free_forever = false).

UPDATE users
SET is_free_forever = true
WHERE is_free_forever = false;
